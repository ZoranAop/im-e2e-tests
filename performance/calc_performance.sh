#!/usr/bin/env bash
# ============================================================
# IM 服务性能估算计算器
# ============================================================
# 根据已知的性能基准数据，估算不同规模和配置下的消息吞吐能力
#
# 用法:
#   bash calc_performance.sh                # 交互模式
#   bash calc_performance.sh --single-chat  # 估算单聊容量
#   bash calc_performance.sh --group-chat   # 估算群聊容量
#   bash calc_performance.sh --chatroom     # 估算聊天室容量
#   bash calc_performance.sh --cluster      # 估算集群容量
#   bash calc_performance.sh --all          # 显示所有估算模型
#
# ============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
source "${SCRIPT_DIR}/config.sh"

MODE="${1:---all}"

print_model_header() {
    echo ""
    echo -e "${BLUE}════════════════════════════════════════════════════════════${NC}"
    echo -e "${BLUE}  $1${NC}"
    echo -e "${BLUE}════════════════════════════════════════════════════════════${NC}"
    echo ""
}

# ============================================================
# 消息处理阶段模型
# ============================================================

print_message_stages() {
    print_model_header "消息处理阶段性能模型"

    cat << 'MODEL'
  发送一条消息包含以下 5 个阶段:

  ┌──────────┬─────────────────────────┬─────────────────────┬──────────────┐
  │ 阶段     │ 描述                    │ 单核速率（16C48G）    │ 测试来源      │
  ├──────────┼─────────────────────────┼─────────────────────┼──────────────┤
  │ 发送阶段 │ 请求→落库→确认           │ 1,227 条/秒/核       │ 单聊发送测试  │
  │ 分发阶段 │ 目标时间线插入落库        │ 8,750 条/秒/核       │ 群聊分发测试  │
  │ 通知阶段 │ 推送通知给在线客户端      │ ≈ 2,978 条/秒/核     │ 收发-发送推导 │
  │ 拉取阶段 │ 客户端请求并返回消息      │                     │              │
  │ 推送阶段 │ HTTP 调用推送服务         │ 低开销              │ -            │
  └──────────┴─────────────────────────┴─────────────────────┴──────────────┘

  通知+拉取速率推导:
  1 ÷ 收发单核速率 = 1 ÷ 发送单核速率 + 1 ÷ (通知+拉取)单核速率
  1 ÷ 869 = 1 ÷ 1227 + 1 ÷ x  →  x ≈ 2,978 条/秒/核

MODEL
}

# ============================================================
# 单聊容量估算
# ============================================================

calc_single_chat() {
    print_model_header "单聊消息容量估算"

    cat << 'MODEL'

  单聊消息开销模型:
  
  单聊消息整体单核速率 = 1 ÷ (1÷发送 + 1÷分发)
                      = 1 ÷ (1÷1227 + 1÷8750)
                      = 1,077 条/秒/核
  
  容量估算公式:
  
  所需核心数 = 预估消息量(条/秒) ÷ 1,077 × 安全系数(≥1.5)
  
  ┌─────────────────┬────────────────┬──────────────┬──────────────────┐
  │ 预估消息量/秒    │ 所需核心数      │ 推荐 IM 规格  │ 可支撑并发用户数   │
  ├─────────────────┼────────────────┼──────────────┼──────────────────┤
  │ 1,000           │ 1.4 → 2        │ 2C8G         │ ~10 万            │
  │ 5,000           │ 7.0 → 8        │ 8C32G        │ ~50 万            │
  │ 10,000          │ 14.0 → 16      │ 16C32G       │ ~100 万           │
  │ 20,000          │ 28.0 → 32      │ 32C64G       │ ~200 万           │
  │ 50,000          │ 69.6 → 80      │ 集群 10×8C    │ ~500 万+          │
  │ 100,000         │ 139 → 160      │ 集群 20×8C    │ ~1,000 万+        │
  └─────────────────┴────────────────┴──────────────┴──────────────────┘

  说明:
  - 以上为发送阶段估算，如接收方在线则需考虑通知+拉取开销
  - 安全系数 1.5 留有余量应对峰值流量
  - 媒体类消息压力主要在对象存储，IM 服务只处理 2 次交互
  - 消息体越大性能越差，大消息场景需单独压测

MODEL
}

# ============================================================
# 群聊容量估算
# ============================================================

calc_group_chat() {
    print_model_header "群聊消息容量估算"

    cat << 'MODEL'

  群聊消息开销模型:
  
  群聊单核速率(条/秒) = 单核分发速率 ÷ 群成员数
                      = 8,750 ÷ 群成员数
  
  群聊主要开销在分发阶段，单核分发速率稳定在约 8,750 条/秒/核。
  
  ┌─────────────────────────────────────────────────────────────────┐
  │ 示例: 预估 100 人活跃群，每秒 20 条消息，需要多少核心？          │
  │                                                                 │
  │ 每核每秒可分发的目标数 = 8,750                                   │
  │ 每条消息分发给 100 人，消耗 = 100 ÷ 8,750 ≈ 0.0114 核            │
  │ 20 条消息/秒 → 20 × 0.0114 = 0.228 核                           │
  │ 加上安全系数 1.5 → 0.34 核（极少）                               │
  └─────────────────────────────────────────────────────────────────┘

  群规模对应关系:
  
  ┌──────────┬──────────────┬──────────────┬───────────────────┐
  │ 群规模   │ 每核每秒能发 │ 20条/秒所需核│ 推荐规格           │
  ├──────────┼──────────────┼──────────────┼───────────────────┤
  │ 100 人群 │ 87.5 条/核   │ 0.3 → 1 核   │ 2C8G 即够         │
  │ 200 人群 │ 43.75 条/核  │ 0.6 → 1 核   │ 2C8G 即够         │
  │ 500 人群 │ 17.5 条/核   │ 1.7 → 2 核   │ 4C16G             │
  │ 1,000人群│ 8.75 条/核   │ 3.4 → 4 核   │ 4C16G             │
  │ 2,000人群│ 4.37 条/核   │ 6.8 → 8 核   │ 8C32G             │
  └──────────┴──────────────┴──────────────┴───────────────────┘

  CPU 利用率为 100% 说明无瓶颈，群聊链路短，性能高效。

MODEL
}

# ============================================================
# 聊天室容量估算
# ============================================================

calc_chatroom() {
    print_model_header "聊天室容量估算"

    cat << 'MODEL'

  聊天室消息开销模型:
  
  聊天室消息主要走内存广播，数据库压力可忽略。
  稳定后单核广播与拉取速率 ≈ 13,000 条/秒/核。
  
  聊天室规模对性能的影响:
  
  ┌────────────┬──────────────┬─────────────────────┐
  │ 聊天室人数 │ 单核发送速率  │ 单核广播拉取速率      │
  ├────────────┼──────────────┼─────────────────────┤
  │ 1,000      │ 32 条/秒/核  │ 32,000 条/秒/核      │
  │ 2,000      │ 12.9 条/秒/核│ 25,773 条/秒/核      │
  │ 5,000      │ 2.7 条/秒/核 │ 13,440 条/秒/核      │
  └────────────┴──────────────┴─────────────────────┘

  特点:
  - 聊天室消息允许少量丢失（设计使然，实时 > 可靠性）
  - CPU 利用率可能受网络瓶颈限制（最高 80%）
  - 5,000 人以上消息基本不再丢失
  - 随着人数增加，单条消息发送耗时增加，单位时间消息量减少
  - 用户单位时间消息量降低 → 丢消息比例降低

MODEL
}

# ============================================================
# 集群容量估算
# ============================================================

calc_cluster() {
    print_model_header "集群容量估算"

    cat << 'MODEL'

  集群扩展模型（4C8G 节点，单聊消息）:
  
  基本规律: 每增加 1 个节点，系统整体吞吐增加约单节点能力的 50%
  
  单节点吞吐 = 6,537 条/秒（4C8G 单核 1,634 条/秒）
  
  ┌──────────┬──────────┬────────────────────┬────────────────┐
  │ 节点数   │ 总核心数 │ 总体吞吐量          │ 扩展系数        │
  ├──────────┼──────────┼────────────────────┼────────────────┤
  │ 1        │ 4C       │ 6,537 条/秒         │ 1.0× (基准)    │
  │ 2        │ 8C       │ 9,459 条/秒         │ 1.5×           │
  │ 3        │ 12C      │ 13,400 条/秒        │ 2.0×           │
  │ 4        │ 16C      │ 16,080 条/秒        │ 2.5×           │
  │ N        │ N×4C     │ ≈ 6,537×(1+(N-1)×0.5) │              │
  └──────────┴──────────┴────────────────────┴────────────────┘

  容量估算公式:
  N 节点吞吐量 ≈ 单节点吞吐量 × (1 + (N-1) × 0.5)

  RPC 与本地处理模型:
  - 本地消息单核速率: 1,634 条/秒/核
  - RPC 消息单核速率: ≈ 800 条/秒/核（约为本地的 50%）
  - N 节点时 RPC 比例 = (N-1)/N
  
  带数据库开销修正（IM:DB 资源比 2:1）:
  - 本地单核速率(含DB): 1,089 条/秒/核
  - RPC 单核速率(含DB):  533 条/秒/核

  集群测试注意事项:
  - 每轮测试执行 2 次，第 1 次热机，以第 2 次数据为准
  - 节点加入后等待 ≥ 3 分钟，完成缓存迁移
  - 每次测试后等待 IM 服务 load 降至接近 0
  - DB 资源配置 ≥ IM 总核心数 ÷ 2

MODEL
}

# ============================================================
