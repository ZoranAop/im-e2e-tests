calc_long_connection() {
    print_model_header "长连接容量估算"

    cat << 'MODEL'

  长连接容量模型:
  
  16C32G 单机可支撑约 100 万并发长连接，CPU ≈ 10 核，MySQL = 0%
  
  估算关系:
  - 每 1 万连接 ≈ 0.1 核 CPU
  - 每 16C 支撑约 100 万连接（留有余量）
  
  ┌──────────────┬────────────────┬──────────────┐
  │ 预期连接数   │ 推荐核心数      │ 推荐 IM 规格  │
  ├──────────────┼────────────────┼──────────────┤
  │ 10 万        │ 2C             │ 2C4G         │
  │ 50 万        │ 8C             │ 8C16G        │
  │ 100 万       │ 16C            │ 16C32G       │
  │ 200 万       │ 32C            │ 32C64G 或集群 │
  │ 500 万       │ 80C            │ 集群         │
  └──────────────┴────────────────┴──────────────┘

  系统调优要求:
  - 文件描述符上限 ≥ 连接数 + 10,000
  - 启用 netty.epoll = true
  - 关闭 embed.db，使用外部 MySQL
  - 单台压测机不超过 6 万模拟连接

MODEL
}

# ============================================================
# 综合估算工具
# ============================================================

calc_custom() {
    print_model_header "自定义容量估算"

    echo -e "${YELLOW}请输入预估参数（留空使用默认值）:${NC}"
    echo ""

    read -p "  消息类型 (1=单聊, 2=群聊, 3=聊天室, 4=长连接): " msg_type
    read -p "  预估每秒消息量: " msg_per_sec
    read -p "  群/聊天室人数（群聊/聊天室）: " member_count
    read -p "  服务器单机核心数: " cores
    read -p "  安全系数 (默认 1.5): " safety_factor

    msg_type="${msg_type:-1}"
    msg_per_sec="${msg_per_sec:-1000}"
    cores="${cores:-16}"
    safety_factor="${safety_factor:-1.5}"

    local rate_per_core=0

    case "${msg_type}" in
        1)
            rate_per_core=1077
            ;;
        2)
            member_count="${member_count:-500}"
            rate_per_core=$(echo "scale=0; 8750 / ${member_count}" | bc 2>/dev/null || echo "17")
            ;;
        3)
            member_count="${member_count:-2000}"
            rate_per_core=$(echo "scale=0; 13000 / ${member_count}" | bc 2>/dev/null || echo "6")
            ;;
        4)
            rate_per_core=62500  # 每核约 6.25 万连接
            ;;
        *)
            echo "无效的消息类型"; return 1
            ;;
    esac

    echo ""
    echo -e "${CYAN}════════════════════════════════════════════════════════════${NC}"
    echo -e "${CYAN}  估算结果${NC}"
    echo -e "${CYAN}════════════════════════════════════════════════════════════${NC}"

    local needed_cores=$(echo "scale=1; ${msg_per_sec} / ${rate_per_core} * ${safety_factor}" | bc 2>/dev/null || echo "N/A")
    local max_capacity=$(echo "scale=0; ${cores} * ${rate_per_core} / ${safety_factor}" | bc 2>/dev/null || echo "N/A")

    echo ""
    echo -e "  每核处理能力: ${GREEN}${rate_per_core}${NC} 条/秒/核"
    echo -e "  所需核心数（含 ${safety_factor}× 安全系数）: ${GREEN}${needed_cores}${NC} 核"
    echo -e "  ${cores} 核可支撑峰值: ${GREEN}${max_capacity}${NC} 条/秒"
    echo ""
}

# ============================================================
# 主入口
# ============================================================

main() {
    case "${MODE}" in
        --single-chat|-sc)
            print_message_stages
            calc_single_chat
            ;;
        --group-chat|-gc)
            calc_group_chat
            ;;
        --chatroom|-cr)
            calc_chatroom
            ;;
        --cluster|-cl)
            calc_cluster
            ;;
        --long-connection|-lc)
            calc_long_connection
            ;;
        --custom|-cu)
            calc_custom
            ;;
        --all|-a)
            print_message_stages
            calc_single_chat
            calc_group_chat
            calc_chatroom
            calc_cluster
            calc_long_connection
            ;;
        *)
            echo "用法: $0 [选项]"
            echo ""
            echo "  --single-chat, -sc    单聊消息容量估算"
            echo "  --group-chat, -gc     群聊消息容量估算"
            echo "  --chatroom, -cr       聊天室容量估算"
            echo "  --cluster, -cl        集群容量估算"
            echo "  --long-connection, -lc 长连接容量估算"
            echo "  --custom, -cu         自定义估算"
            echo "  --all, -a             显示所有估算模型（默认）"
            exit 1
            ;;
    esac
}

main
